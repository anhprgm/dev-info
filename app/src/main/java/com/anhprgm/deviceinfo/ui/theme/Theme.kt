/**
 * Status colours resolved for the current brightness, exposed so gauges can
 * stay semantically red/amber/green even under Material You recolouring.
 */
data class StatusPalette(val good: Color, val warning: Color, val critical: Color)

val LocalStatusPalette = staticCompositionLocalOf {
    StatusPalette(StatusColors.good, StatusColors.warning, StatusColors.critical)
}

/** True when the resolved scheme is dark, regardless of how it was chosen. */
val LocalIsDarkTheme = staticCompositionLocalOf { false }

@Composable
fun DevInfoTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val dark = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }

    val context = LocalContext.current
    val colorScheme = when {
        // Material You is only available from API 31.
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)

        dark -> DarkColors
        else -> LightColors
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        // Only the bar icon appearance is set here. The old code assigned
        // window.statusBarColor (deprecated, and a no-op edge-to-edge), which
        // also painted the bar with `primary` while the top app bar used
        // `surface` — a visible seam on the start screen.
        DisposableEffect(dark) {
            val window = (view.context as android.app.Activity).window
            val controller = WindowCompat.getInsetsController(window, view)
            controller.isAppearanceLightStatusBars = !dark
            controller.isAppearanceLightNavigationBars = !dark
            onDispose { }
        }
    }

    val statusPalette = if (dark) {
        StatusPalette(StatusColors.goodDark, StatusColors.warningDark, StatusColors.criticalDark)
    } else {
        StatusPalette(StatusColors.good, StatusColors.warning, StatusColors.critical)
    }

    CompositionLocalProvider(
        LocalStatusPalette provides statusPalette,
        LocalIsDarkTheme provides dark
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = DevInfoTypography,
            shapes = DevInfoShapes,
            content = content
        )
    }
}
